function [q1,q2,q3] = DAR_Solver(Target,L1,L2,L3,S)
%==========================================================================
% DAR_SOLVER
%
% Adaptación del método Directed Angular Restitution (DAR)
% para el robot cuadrúpedo AMTQ.
%
% Entradas
%
% Target = [x;y;z]
% L1,L2,L3 = longitudes
% S = simetría (+1/-1)
%
% Salidas
%
% q1,q2,q3 [rad]
%
%==========================================================================

%% Parámetros

tol = 1e-3;      % mm

maxIter = 40;

%% Estado inicial

q1 = 0;
q2 = 0;
q3 = 0;

%%==========================================================
%% Iteraciones DAR
%%==========================================================

for k = 1:maxIter

    %%------------------------------------------------------
    %% CINEMÁTICA DIRECTA
    %%------------------------------------------------------

    J1 = [0;0;0];

    % Coxa
    J2 = J1 + ...
        [ L1*cos(q1);
          L1*sin(q1);
          0 ];

    % Fémur
    J3 = J2 + ...
        [ L2*cos(q2)*cos(q1);
          L2*cos(q2)*sin(q1);
          L2*sin(q2)];

    % Tibia
    Foot = J3 + ...
        [ L3*cos(q2+q3)*cos(q1);
          L3*cos(q2+q3)*sin(q1);
          L3*sin(q2+q3)];

    %%------------------------------------------------------
    %% DAR
    %%------------------------------------------------------

    [dq1,dq2,dq3] = DAR_Iteration( ...
        J1,...
        J2,...
        J3,...
        Foot,...
        Target);

    %%------------------------------------------------------
    %% ACTUALIZAR ÁNGULOS
    %%------------------------------------------------------

    q1 = q1 + dq1;

    q2 = q2 + dq2;

    q3 = q3 + dq3;

    %%------------------------------------------------------
    %% ERROR
    %%------------------------------------------------------

    err = norm(Target-Foot);

    if err < tol
        break;
    end

end

%%----------------------------------------------------------
%% Offsets del AMTQ
%%----------------------------------------------------------

q1 = q1 - S*0.4636;

q2 = q2 - 0.1273;

q3 = q3 - 1.8338;

end