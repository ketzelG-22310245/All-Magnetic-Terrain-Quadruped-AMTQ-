function theta = DAR_Angle(r_ab,r_ac,axis,method)
%==========================================================================
% DAR_ANGLE
%
% Directed Angular Restitution
%
% Implementación basada en Lizarraga et al.
%
% Ecuaciones (1)-(3)
%
% r_ab : Vector AB
% r_ac : Vector AC
%
% axis : 'x','y','z'
%
% method
%   1 -> Eq.(1)
%   2 -> Eq.(2)
%   3 -> Eq.(3) (Recomendada)
%
%==========================================================================

%%======================================================================
%% Elimination Vector
%%======================================================================

switch lower(axis)

    case 'x'

        E = [0;1;1];
        axisVector = [1;0;0];

    case 'y'

        E = [1;0;1];
        axisVector = [0;1;0];

    case 'z'

        E = [1;1;0];
        axisVector = [0;0;1];

    otherwise

        error('Invalid rotation axis.');

end

%%======================================================================
%% Hadamard Operator
%%======================================================================

v1 = E .* r_ab;
v2 = E .* r_ac;

%%======================================================================
%% Numerical protection
%%======================================================================

if norm(v1) < eps || norm(v2) < eps

    theta = 0;
    return;

end

%%======================================================================
%% Normalization
%%======================================================================

v1 = v1 / norm(v1);
v2 = v2 / norm(v2);

%%======================================================================
%% Dot and Cross Products
%%======================================================================

dotProduct = dot(v1,v2);

dotProduct = max(min(dotProduct,1),-1);

crossProduct = cross(v1,v2);

%%======================================================================
%% Projection over rotation axis
%%======================================================================

crossProjection = dot(crossProduct,axisVector);

%%======================================================================
%% Spin Function
%%======================================================================

spin = DAR_Spin(r_ab,r_ac,axis);

%%======================================================================
%% DAR Equations
%%======================================================================

switch method

    %--------------------------------------------------------------
    % Equation (1)
    %--------------------------------------------------------------

    case 1

        theta = acos(dotProduct);

    %--------------------------------------------------------------
    % Equation (2)
    %--------------------------------------------------------------

    case 2

        value = spin * crossProjection;

        value = max(min(value,1),-1);

        theta = asin(value);

    %--------------------------------------------------------------
    % Equation (3)
    %--------------------------------------------------------------

    otherwise

        theta = atan2( ...
                    spin*crossProjection,...
                    dotProduct);

end

end